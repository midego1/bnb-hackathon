#!/usr/bin/env node
// Regenerates the frontend's contract bindings from the Foundry build output.
//
//   1. ABIs:        ../contracts/out/<Name>.sol/<Name>.json  ->  lib/contracts/abis.generated.ts
//   2. Deployments: ../contracts/deployments/<chainId>.json  ->  lib/contracts/deployments.generated.json
//      (falls back to <chainId>.example.json, the deterministic fresh-anvil deployment, when the real file is
//      absent; local deployment files are gitignored)
//
// Run `cd contracts && forge build` first, then `pnpm -C web sync:contracts`. Both outputs are committed so
// `next build` never needs Foundry; regenerate them whenever the contracts change.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const web = join(dirname(fileURLToPath(import.meta.url)), "..");
const contracts = join(web, "..", "contracts");
const outDir = join(web, "lib", "contracts");
const NAMES = { EscrowFactory: "escrowFactoryAbi", RentalEscrow: "rentalEscrowAbi", MockUSDT: "mockUsdtAbi", FleetVault: "fleetVaultAbi" };
// Deploy output directory relative to contracts/ (the Playwright run uses its own, e.g. deployments/.e2e-web).
const DEPLOYMENTS_DIR = process.env.DEPLOYMENTS_DIR ?? "deployments";

// --- ABIs ---------------------------------------------------------------------------------------
let ts = "// GENERATED by web/scripts/sync-contracts.mjs from contracts/out. Do not edit by hand.\n\n";
for (const [name, id] of Object.entries(NAMES)) {
  const file = join(contracts, "out", `${name}.sol`, `${name}.json`);
  if (!existsSync(file)) {
    console.error(`missing ${file}: run \`cd contracts && forge build\` first`);
    process.exit(1);
  }
  const { abi } = JSON.parse(readFileSync(file, "utf8"));
  ts += `export const ${id} = ${JSON.stringify(abi, null, 2)} as const;\n\n`;
}
writeFileSync(join(outDir, "abis.generated.ts"), ts);
console.log(`abis: ${Object.keys(NAMES).join(", ")} -> lib/contracts/abis.generated.ts`);

// --- Deployments --------------------------------------------------------------------------------
// Accepts loosely-named keys so the deploy script's exact format can evolve without touching the app.
const pick = (obj, patterns) => {
  for (const [k, v] of Object.entries(obj)) {
    if (typeof v === "string" && patterns.some((p) => p.test(k))) return v;
  }
  return undefined;
};
const pickNumber = (obj, patterns) => {
  for (const [k, v] of Object.entries(obj)) {
    if ((typeof v === "number" || typeof v === "string") && patterns.some((p) => p.test(k))) return Number(v);
  }
  return undefined;
};
function normalise(raw) {
  const flat = { ...raw, ...(raw.contracts ?? {}), ...(raw.addresses ?? {}) };
  const entry = {
    escrowFactory: pick(flat, [/^escrowfactory$/i, /^factory$/i]),
    mockUsdt: pick(flat, [/^mockusdt$/i, /^usdt$/i, /^token$/i, /^stablecoin$/i]),
    disputeDesk: pick(flat, [/^defaultarbiter$/i, /^disputedesk$/i]),
    fleetVault: pick(flat, [/^fleetvault$/i]),
    atlasSwapGuard: pick(flat, [/^atlasswapguard$/i]),
    rentalEscrowImplementation: pick(flat, [/^rentalescrowimplementation$/i]),
    fromBlock: pickNumber(flat, [/^startblock$/i, /^fromblock$/i, /^deployblock$/i, /^blocknumber$/i, /^block$/i]) ?? 0,
    // Read from the token itself by Deploy.s.sol (decimals() / symbol()); the app never assumes 6.
    tokenDecimals: pickNumber(flat, [/^tokendecimals$/i]),
    tokenSymbol: pick(flat, [/^tokensymbol$/i]),
  };
  if (!entry.escrowFactory || !entry.mockUsdt || entry.tokenDecimals === undefined) return undefined;
  return entry;
}

const target = join(outDir, "deployments.generated.json");
const depDir = join(contracts, DEPLOYMENTS_DIR);
const current = existsSync(target) ? JSON.parse(readFileSync(target, "utf8")) : {};
if (existsSync(depDir)) {
  const next = { ...current };
  const files = readdirSync(depDir);
  const chainIds = [...new Set(files.map((f) => /^(\d+)(\.example)?\.json$/.exec(f)?.[1]).filter(Boolean))];
  for (const chainId of chainIds) {
    const f = files.includes(`${chainId}.json`) ? `${chainId}.json` : `${chainId}.example.json`;
    const entry = normalise(JSON.parse(readFileSync(join(depDir, f), "utf8")));
    if (entry) next[chainId] = entry;
    else console.warn(`${DEPLOYMENTS_DIR}/${f}: no factory/token address or tokenDecimals found, skipped`);
  }
  writeFileSync(target, JSON.stringify(next, null, 2) + "\n");
  console.log(`deployments: ${Object.keys(next).join(", ")} -> lib/contracts/deployments.generated.json`);
} else {
  console.log("deployments: contracts/deployments/ not found, kept lib/contracts/deployments.generated.json");
}
